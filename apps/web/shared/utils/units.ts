const BLUE_WHALE_DISABLED_UNITS: readonly string[] = [
  '06', // 藍鯨規劃書 §2.1（行 92、135）：總則四項例外之一，不設 06 女子足球（自我指涉）
  '11', // 藍鯨規劃書 §2.1（行 92、135）：總則四項例外之一，不設 11 慈善與社會影響（主辦是協會，與藍鯨無關）
  '4.7', // 藍鯨規劃書 §3.4（行 197）：總則四項例外之一，04 青年隊「不沿用招生與課程報名架構」，4.7 整頁即為該架構
  '8.1', // 藍鯨規劃書 §2.1（行 136）：總則五項例外之一（v1.9，2026-09-30 客戶回覆台中藍鯨沒有漫畫），08 不設 8.1 漫畫；`culture/manga` 頁面宣告 unit '8.1'
  '12.2', // 藍鯨規劃書 §3.4（行 197）：依附 4.7 同一項例外，`faq/academy-admission/index.vue` 頁面本身宣告 unit '12.2'，必須列在這裡 middleware 才會擋（BW-C1 修正：先前誤以為只需寫進下方 FAQ_CATEGORY_UNIT_CODES 就夠，漏了頁面本身的 unit-gate 檢查，見 docs/18-work-errors.md）
]

export function isUnitEnabledForClub(unitCode: string, club: string): boolean {
  const normalizedClub: ClubCode = club === 'bw' ? 'bw' : 'tcrfc'
  if (normalizedClub === 'bw' && BLUE_WHALE_DISABLED_UNITS.includes(unitCode)) {
    return false
  }
  return true
}

// FAQ（單元 12）分類 slug → 細粒度單元代號對照，供分類本身（沒有自己的路由、
// 無法直接掛 definePageMeta）判斷是否要對某俱樂部隱藏。
//
// 只留 '12.2'（依附於 4.7 同一項總則例外，見上方說明）。'12.3'（課程與營隊報名）
// 已隨 5.1–5.4 於 BW-C1 重開，移除對照（見上方檔頭說明），不再關閉。
export const FAQ_CATEGORY_UNIT_CODES: Readonly<Record<string, string>> = {
  'academy-admission': '12.2', // 藍鯨規劃書 §3.4（行 197）：內容是磐石學院招生流程問答，依附 4.7 同一項例外
}

export function isFaqCategoryEnabledForClub(categorySlug: string, club: string): boolean {
  const unitCode = FAQ_CATEGORY_UNIT_CODES[categorySlug]
  if (!unitCode) return true
  return isUnitEnabledForClub(unitCode, club)
}
